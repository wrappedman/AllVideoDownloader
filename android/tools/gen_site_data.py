#!/usr/bin/env python3
"""Generate `SiteRegistry.kt` from the Python recipe table.

The Android port keeps `webfinder/core/sites.py` as the single source of truth:
this script imports the real module and emits the same 384 recipes / 717
hostnames, the same player-family patterns, the same family markers and the same
embed-host table as Kotlin data. Nothing is re-typed by hand, so the Android
registry cannot drift from the desktop one.

    python3 android/tools/gen_site_data.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from webfinder.core import sites  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/allvideodownloader/avd/core/SiteRegistry.kt"


def kt(s: str) -> str:
    """Kotlin raw-safe string literal (no template expansion)."""
    out = (s.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
            .replace("$", "\\$"))
    return f'"{out}"'


def flags_of(pattern: re.Pattern) -> str:
    names = []
    if pattern.flags & re.IGNORECASE:
        names.append("Pattern.CASE_INSENSITIVE")
    if pattern.flags & re.DOTALL:
        names.append("Pattern.DOTALL")
    if pattern.flags & re.MULTILINE:
        names.append("Pattern.MULTILINE")
    names.append("Pattern.UNICODE_CASE")
    return " or ".join(names)


def main() -> None:
    lines: list[str] = []
    a = lines.append

    a("package com.allvideodownloader.avd.core")
    a("")
    a("// GENERATED by android/tools/gen_site_data.py from webfinder/core/sites.py.")
    a("// Do not edit by hand: run the generator instead, so the Android registry")
    a("// always matches the desktop recipe table exactly.")
    a("")
    a("import java.util.regex.Pattern")
    a("")
    a("/** One declarative recipe: a site name + its hostnames + player family. */")
    a("data class Recipe(")
    a("    val key: String,")
    a("    val name: String,")
    a("    val domains: List<String>,")
    a("    val family: String = \"generic\",")
    a("    val note: String = \"\",")
    a("    val adapter: String = \"\",")
    a(")")
    a("")
    a("/** A label-carrying player-family pattern (group 1 = media URL). */")
    a("class FamilyPattern(val regex: Pattern, val label: String)")
    a("")
    a("/** An <iframe> player host we recognise by URL shape. */")
    a("class EmbedHost(val regex: Pattern, val label: String)")
    a("")
    a("object SiteRegistry {")
    a("")
    a("    const val RECIPE_COUNT = %d" % len(sites.RECIPES))
    a("")
    a("    val RECIPES: List<Recipe> = listOf(")
    for r in sites.RECIPES:
        doms = ", ".join(kt(d) for d in r.domains)
        a(f'        Recipe({kt(r.key)}, {kt(r.name)}, listOf({doms}), {kt(r.family)}, '
          f'{kt(r.note)}, {kt(r.adapter)}),')
    a("    )")
    a("")
    a("    val FAMILIES: Map<String, List<FamilyPattern>> = mapOf(")
    for fam, pats in sites.FAMILIES.items():
        a(f'        {kt(fam)} to listOf(')
        for pat, label in pats:
            a(f'            FamilyPattern(Pattern.compile({kt(pat.pattern)}, {flags_of(pat)}), {kt(label)}),')
        a("        ),")
    a("    )")
    a("")
    a("    /** How a page announces its player, whatever the host. */")
    a("    val FAMILY_MARKERS: List<Pair<String, Pattern>> = listOf(")
    for name, pat in sites._FAMILY_MARKERS:
        a(f'        {kt(name)} to Pattern.compile({kt(pat.pattern)}, {flags_of(pat)}),')
    a("    )")
    a("")
    a("    /** Cross-origin player hosts: an <iframe> at one of these IS the video. */")
    a("    val EMBED_HOSTS: List<EmbedHost> = listOf(")
    for pat, name in sites.EMBED_HOSTS:
        a(f'        EmbedHost(Pattern.compile({kt(pat.pattern)}, {flags_of(pat)}), {kt(name)}),')
    a("    )")
    a("}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines, {len(sites.RECIPES)} recipes)")


if __name__ == "__main__":
    main()
